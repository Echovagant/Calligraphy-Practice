// 笔画类型 → 笔画字典分类的映射。
// 笔顺数据给出的是「这一笔是什么笔画」，笔画字典（strokeDictionary.js）给的是
// 「这一类笔画怎么写」。两者通过 category 对接。
// 字典里的分类：横画类 / 竖画类 / 撇画类 / 捺画类 / 点画类 / 折笔类 / 折画类 /
//               钩画类 / 提画类

const CATEGORY = {
  横: '横画类',
  竖: '竖画类',
  撇: '撇画类',
  捺: '捺画类',
  点: '点画类',
  提: '提画类',

  横折: '折笔类',
  横折弯: '折笔类',
  竖折: '折画类',
  撇折: '折画类',

  横撇: '撇画类',
  竖撇: '撇画类',
  横折折撇: '撇画类',
  撇点: '撇画类',

  竖提: '提画类',
  横折提: '提画类',

  横钩: '钩画类',
  横折钩: '钩画类',
  竖钩: '钩画类',
  竖弯钩: '钩画类',
  弯钩: '钩画类',
  卧钩: '钩画类',
  横斜钩: '钩画类',
  横折斜钩: '钩画类',
  横折折钩: '钩画类',
  竖折折钩: '钩画类',
  横折弯钩: '钩画类',
};

export const STROKE_TYPE_CATEGORY = CATEGORY;

/** 某一笔的类型属于哪一类；未知类型返回 null */
export function strokeTypeCategory(type) {
  return CATEGORY[type] || null;
}
